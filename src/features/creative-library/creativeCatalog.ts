export function blendColorWithIntensity(
  target: Partial<ClipColorAdjustments>,
  intensityPct: number
): ClipColorAdjustments {
  const t = Math.max(0, Math.min(1, intensityPct / 100));
  const lerp = (base: number, goal?: number) => {
    const g = goal ?? base;
    return Math.round((base + (g - base) * t) * 10) / 10;
  };
  return {
    brightness: lerp(DEFAULT_COLOR.brightness, target.brightness),
    contrast: lerp(DEFAULT_COLOR.contrast, target.contrast),
    saturation: lerp(DEFAULT_COLOR.saturation, target.saturation),
    hueRotate: lerp(DEFAULT_COLOR.hueRotate, target.hueRotate),
    temperature: lerp(DEFAULT_COLOR.temperature, target.temperature),
    grayscale: lerp(DEFAULT_COLOR.grayscale, target.grayscale),
    sepia: lerp(DEFAULT_COLOR.sepia, target.sepia),
    blur: lerp(DEFAULT_COLOR.blur, target.blur),
    vignette: lerp(DEFAULT_COLOR.vignette, target.vignette),
    curveShadows: lerp(DEFAULT_COLOR.curveShadows, target.curveShadows),
    curveMidtones: lerp(DEFAULT_COLOR.curveMidtones, target.curveMidtones),
    curveHighlights: lerp(DEFAULT_COLOR.curveHighlights, target.curveHighlights),
  };
}

const FAV_FILTERS_KEY = 'framestudio_favorite_filters_v1';
const CUSTOM_FILTERS_KEY = 'framestudio_custom_filters_v1';

export function loadFavoriteFilterIds(): string[] {
  try {
    const raw = localStorage.getItem(FAV_FILTERS_KEY);
    if (!raw) return [];
    const parsed = JSON.parse(raw);
    return Array.isArray(parsed) ? parsed : [];
  } catch {
    return [];
  }
}

export function saveFavoriteFilterIds(ids: string[]): void {
  try {
    localStorage.setItem(FAV_FILTERS_KEY, JSON.stringify(ids));
  } catch {
    // ignore storage errors
  }
}

