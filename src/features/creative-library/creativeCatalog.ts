export function createEffectItemFromDef(def: VideoEffectDefinition): VideoEffectItem {
  return {
    id: createId('vfx'),
    type: def.type,
    name: def.name,
    category: def.category,
    enabled: true,
    intensity: def.defaultIntensity,
    speed: def.defaultSpeed,
    scale: def.defaultScale,
    angle: def.defaultAngle,
    tint: def.defaultTint,
  };
}

